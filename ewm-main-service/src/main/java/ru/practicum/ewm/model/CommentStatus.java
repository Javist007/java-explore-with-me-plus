package ru.practicum.ewm.model;

/**
 * Статус комментария в процессе премодерации.
 */
public enum CommentStatus {
    /**
     * Ожидает решения администратора, публично не виден.
     */
    PENDING,
    /**
     * Подтверждён администратором и виден всем.
     */
    PUBLISHED,
    /**
     * Отклонён администратором.
     */
    REJECTED
}
