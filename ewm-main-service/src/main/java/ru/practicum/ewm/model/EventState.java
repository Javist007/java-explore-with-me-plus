package ru.practicum.ewm.model;

/**
 * Состояние жизненного цикла события.
 */
public enum EventState {
    /**
     * Событие ожидает публикации (на модерации).
     */
    PENDING,
    /**
     * Событие опубликовано и доступно для просмотра.
     */
    PUBLISHED,
    /**
     * Событие отменено инициатором или администратором.
     */
    CANCELED
}
